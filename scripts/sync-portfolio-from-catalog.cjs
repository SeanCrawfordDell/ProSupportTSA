#!/usr/bin/env node
"use strict";
// Rebuilds js/portfolio-data.js from the ISG Tools Catalog's src/data/tools.json.
//   node scripts/sync-portfolio-from-catalog.cjs path/to/ISGToolsCatalog/src/data/tools.json [today YYYY-MM-DD]
// The catalog has no health, stage or weekly status of its own, so this script maps what it does have:
//   status   -> stage (planning: Intake, development: Build, testing/internal-testing: Test, released/maintenance: Support)
//   roadmap  -> tasks (completed / total), target (next open item's date) and the status note
//   health   -> At risk when an open roadmap item is past its target date, otherwise On track
//   updatedAt -> updated (the date the catalog entry last changed)
const fs = require("node:fs"), path = require("node:path");

const catalogUrl = "https://seancrawforddell.github.io/ISGToolsCatalog/";
const stageFor = { planning: "Intake", development: "Build", testing: "Test", "internal-testing": "Test", released: "Support", maintenance: "Support" };
const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const isDate = value => /^\d{4}-\d{2}-\d{2}$/.test(String(value || ""));
const showDate = value => { const [y, m, d] = value.split("-").map(Number); return `${months[m - 1]} ${d}, ${y}`; };

// "first.last@dell.com" reads as "First Last"; other owners stay as written.
function ownerName(owner) {
  const value = String(owner || "").trim();
  const email = /^([^@\s]+)@[^@\s]+$/.exec(value);
  if (!email) return value;
  return email[1].split(/[._-]+/).filter(Boolean).map(p => p[0].toUpperCase() + p.slice(1).toLowerCase()).join(" ");
}

function toPortfolio(tool, today) {
  const roadmap = Array.isArray(tool.roadmap) ? tool.roadmap : [];
  const open = roadmap.filter(item => item.status !== "completed")
    .sort((a, b) => String(a.targetDate || "9999").localeCompare(String(b.targetDate || "9999")));
  const next = open[0];
  const overdue = open.find(item => isDate(item.targetDate) && item.targetDate < today);
  const stage = stageFor[tool.status] || "Intake";
  let note;
  if (overdue) note = `${overdue.feature} was due ${showDate(overdue.targetDate)}`;
  else if (next) note = `Next: ${next.feature}`;
  else if (stage === "Support") note = "Released; no open roadmap items";
  else note = `${String(tool.status).replace(/-/g, " ")}${typeof tool.progress === "string" ? " · " + tool.progress : ""}`;
  return {
    id: tool.id,
    name: tool.name,
    category: tool.category || "",
    description: tool.description || "",
    link: `${catalogUrl}#/tools/${encodeURIComponent(tool.id)}`,
    owner: ownerName(tool.owner),
    stage,
    health: overdue ? "At risk" : "On track",
    tasksDone: roadmap.length - open.length,
    tasksTotal: roadmap.length,
    target: next && isDate(next.targetDate) ? showDate(next.targetDate) : "",
    note: note.charAt(0).toUpperCase() + note.slice(1),
    updated: isDate(tool.updatedAt) ? tool.updatedAt : ""
  };
}

function build(catalog, today) {
  const tools = (Array.isArray(catalog) ? catalog : catalog.tools || []).map(tool => toPortfolio(tool, today));
  return { source: "ISG Tools Catalog", sourceUrl: catalogUrl, syncedOn: today, staleDays: 180,
    notice: `Synced from the ISG Tools Catalog on ${showDate(today)}. Stage comes from each tool's catalog status, tasks from its roadmap items, and Updated from the date its catalog entry last changed.`,
    tools };
}

function render(data) {
  return `"use strict";
// Tool Portfolio data, generated by scripts/sync-portfolio-from-catalog.cjs from the ISG Tools Catalog.
// Re-run the script after the catalog changes instead of editing this file by hand.
// Fields per tool: id, name, category, description, link, owner, stage (Intake | Design | Build | Test | Release |
// Support), health (On track | At risk | Off track), tasksDone / tasksTotal, target, note, updated (YYYY-MM-DD).
const PortfolioData = ${JSON.stringify(data, null, 2)};
if (typeof window !== "undefined") window.PortfolioData = PortfolioData;
if (typeof module !== "undefined") module.exports = PortfolioData;
`;
}

if (require.main === module) {
  const [source, todayArg] = process.argv.slice(2);
  if (!source) { console.error("Usage: node scripts/sync-portfolio-from-catalog.cjs <tools.json> [YYYY-MM-DD]"); process.exit(1); }
  const today = isDate(todayArg) ? todayArg : new Date().toISOString().slice(0, 10);
  const data = build(JSON.parse(fs.readFileSync(source, "utf8")), today);
  fs.writeFileSync(path.join(__dirname, "..", "js", "portfolio-data.js"), render(data));
  console.log(`Wrote ${data.tools.length} tools to js/portfolio-data.js`);
}
module.exports = { build, render, toPortfolio, ownerName };
